export type UIKey = keyof (typeof ui)['en'];
export const useT = (lang: Lang) => (k: UIKey) => ui[lang][k];

/** Prefix a path for the given language. */
export const href = (lang: Lang, path: string) => {
  const p = path.startsWith('/') ? path : `/${path}`;
  if (lang === 'en') return p;
  return p === '/' ? '/vi/' : `/vi${p}`;
};

/** Given current pathname, return the equivalent path in the other language. */
export const altPath = (pathname: string, to: Lang) => {
  const clean = pathname.replace(/^\/vi(?=\/|$)/, '') || '/';
  return href(to, clean);
};
